#!/usr/bin/env node
'use strict';
/**
 * Writes env.js for a static frontend from environment variables.
 * Run by the host's build step (see frontend/ar/netlify.toml, frontend/dashboard/netlify.toml):
 *
 *   API_BASE_URL=https://<backend>.onrender.com node scripts/write-frontend-env.js frontend/ar
 *   API_BASE_URL=https://<backend>.onrender.com AR_SCANNER_URL=https://arvrca3.netlify.app/ node scripts/write-frontend-env.js frontend/dashboard
 *
 * env.js is loaded before config.js and sets window.__API_BASE_URL (highest priority in
 * config.js). With API_BASE_URL unset it writes an empty value, so config.js falls back to
 * localStorage / http://localhost:3000 exactly as in local dev.
 * AR_SCANNER_URL (dashboard only) sets window.__AR_SCANNER_URL for the "Open AR view"
 * link; empty means config.js uses its default (the live AR Netlify site).
 */
const fs = require('fs');
const path = require('path');

const dirs = process.argv.slice(2);
if (!dirs.length) {
  console.error('usage: node scripts/write-frontend-env.js <frontend-dir> [...]');
  process.exit(1);
}

function cleanOrigin(value) {
  return String(value || '').trim().replace(/\/+$/, '');
}

function validHttpUrl(url) {
  return /^https?:\/\/[^\s'"<>]+$/i.test(url);
}

const url = cleanOrigin(process.env.API_BASE_URL || process.env.AR_API_BASE_URL || '');
if (url && !validHttpUrl(url)) {
  console.error(`API_BASE_URL is not a valid http(s) origin: "${url}"`);
  process.exit(1);
}
if (url && process.env.CONTEXT === 'production' && /localhost|127\.0\.0\.1/.test(url)) {
  console.error('Refusing to deploy a production frontend pointed at localhost.');
  process.exit(1);
}
if (url.endsWith('/api')) console.warn('warning: API_BASE_URL should be the backend ORIGIN (no /api suffix).');

const arUrl = cleanOrigin(process.env.AR_SCANNER_URL || process.env.AR_VIEW_URL || '');
if (arUrl && !validHttpUrl(arUrl)) {
  console.error(`AR_SCANNER_URL is not a valid http(s) URL: "${arUrl}"`);
  process.exit(1);
}

const body = `/* Generated by scripts/write-frontend-env.js at deploy time. Local default: empty. */
window.__API_BASE_URL = window.__API_BASE_URL || ${JSON.stringify(url)};
window.__AR_SCANNER_URL = window.__AR_SCANNER_URL || ${JSON.stringify(arUrl)};
`;
for (const dir of dirs) {
  const out = path.join(dir, 'env.js');
  fs.writeFileSync(out, body);
  console.log(`wrote ${out} (API_BASE_URL=${url || '<empty: dev fallback>'} AR_SCANNER_URL=${arUrl || '<empty: config default>'})`);
}
